export const DEFAULT_PUZZLE_TIMEZONE = process.env.TIMEZONE || "America/New_York";

export const getDateInTimeZone = (timeZone = DEFAULT_PUZZLE_TIMEZONE): string => {
  const formatter = new Intl.DateTimeFormat("en-CA", {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  });

  const parts = formatter.formatToParts(new Date());
  const year = parts.find((part) => part.type === "year")?.value;
  const month = parts.find((part) => part.type === "month")?.value;
  const day = parts.find((part) => part.type === "day")?.value;

  if (!year || !month || !day) {
    throw new Error("Failed to compute date in timezone");
  }

  return `${year}-${month}-${day}`;
};

export const getTodayPuzzleDate = () => getDateInTimeZone();
